-- 업체 대시보드 기획서(docs/plan/tenant-plan.md)가 새로 요구한 것들.
--
-- 그 문서는 프로토타입 이후에 쓰였고, 프로토타입에 없던 요구가 몇 개 들어 있다.
-- 지금 쓰지 않더라도 컬럼은 미리 넣는다 — 데이터가 쌓인 뒤에 ALTER 하는 편이 훨씬 비싸다.

-- ============================================================
-- 1. 공통 질문의 후속 질문 (tenant-plan.md §4.6)
-- ============================================================

-- 답변을 보여준 뒤 이어서 제안할 질문들. api-contracts.md §10 의
-- POST /api/widget/faq/{id} 응답에 이미 followUpFaqIds 로 적혀 있었는데 스키마가 없었다.
--
-- uuid[] 가 아니라 jsonb 인 이유: 조회 조건으로 쓰지 않고 표시용으로만 읽는다.
-- 배열 컬럼을 조회 조건으로 쓰게 되면 그건 조인 테이블이 필요하다는 신호다
-- (.claude/rules/backend-spring-boot.md).
ALTER TABLE faqs ADD COLUMN follow_up_faq_ids jsonb NOT NULL DEFAULT '[]'::jsonb;

-- ============================================================
-- 2. 챗봇 프로필 이미지 (tenant-plan.md §4.7)
-- ============================================================

-- 없으면 이름 첫 글자를 쓴다. 그래서 nullable 이다.
-- TODO(stub): 파일 저장소가 아직 로컬 디스크 구현이다. 업로드 정식 오픈 전에 S3 호환으로 교체.
ALTER TABLE bot_settings ADD COLUMN avatar_url text;

-- ============================================================
-- 3. 유사 질문 묶기 (tenant-plan.md §4.2)
-- ============================================================

-- 기획서는 질문 임베딩 유사도로 묶으라고 한다. 지금 구현은 정규화 키(question_norm)라
-- "제주 배송되나요" 와 "도서지역 배송" 을 묶지 못한다.
--
-- 묶기는 답변 파이프라인이 실패 질문을 적재하는 시점에 일어나므로, 파이프라인이 생길 때
-- 켠다. 임계값은 cost_guards.answer_fail_similarity(기본 0.72)를 쓴다.
-- 그때 ALTER 하지 않도록 컬럼만 먼저 만들어 둔다. nullable 이다 — 지금 들어오는 행은 비어 있다.
--
-- 주의: 실패 질문마다 임베딩 호출이 붙는다. 답변 실패는 원가율이 이미 나쁜 상태에서
-- 더 나오는 것이라, 켤 때 반드시 일일 상한과 함께 켠다.
ALTER TABLE answer_gaps ADD COLUMN question_embedding vector(1536);

-- ============================================================
-- 4. 응답 시간 (tenant-plan.md §4.1 지표 4종 — "평균 응답")
-- ============================================================

-- 홈이 "평균 응답 1.9초"를 보여주려면 잴 곳이 있어야 한다. 답변 파이프라인이
-- BOT 메시지를 만들 때 채운다. 저장 답변(saved=true)은 모델을 거치지 않아 거의 0ms 다 —
-- 함께 평균 내면 실제 체감보다 좋게 나오므로 집계에서 나눠 볼 수 있게 둔다.
--
-- nullable 이다. 파이프라인 이전에 쌓인 메시지는 잰 적이 없고, 0 으로 채우면
-- "0ms 에 답했다"는 거짓이 된다.
ALTER TABLE messages ADD COLUMN latency_ms integer;
