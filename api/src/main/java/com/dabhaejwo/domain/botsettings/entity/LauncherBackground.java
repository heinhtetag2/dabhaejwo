package com.dabhaejwo.domain.botsettings.entity;

/**
 * 런처(동그란 버블)에 올린 이미지 뒤에 무엇을 깔 것인가.
 *
 * <p>PNG 의 투명은 흰색이 아니라 <b>아무것도 안 칠한 것</b>이라, 그 자리로 뒤에 있는 것이
 * 그대로 올라온다. 지금까지는 뒤에 늘 브랜드 색이 있었고 그건 기본 말풍선 아이콘(흰 선)을
 * 기준으로 고른 값이었다 — 업체 로고는 계산에 없었다.
 *
 * <p>한쪽으로 정할 수 없어 업체에게 넘긴다. 흰 바탕 기준으로 만든 로고는 진한 브랜드 색
 * 위에서 뭉개지고, 밝은 브랜드 색에 흰 로고를 올리면 아예 안 보인다. 우리가 고르면
 * 반대쪽 업체가 매번 깨진다.
 *
 * <p><b>이미지가 없으면 이 값은 쓰이지 않는다.</b> 기본 아이콘이 흰 선이라 흰 바탕·투명
 * 위에서는 보이지 않는다 — 서버가 {@code BRAND} 로 강제한다.
 */
public enum LauncherBackground {

    /** 업체가 정한 버블 색. 기존 동작이자 기본값이다. */
    BRAND,

    /** 흰 바탕. 로고는 대개 흰 배경 기준으로 만들어진다. */
    WHITE,

    /**
     * 투명. 남의 사이트 배경이 그대로 비친다.
     *
     * <p>그림자도 함께 없앤다 — 보이지 않는 원의 그림자만 남으면 로고가 얼룩 위에 뜬
     * 것처럼 보인다.
     */
    NONE
}
